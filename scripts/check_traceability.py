"""Check requirement traceability and generate docs/requirements/traceability.md.

Links three things:

- requirements: headings ``#### EA-... Title`` in docs/requirements/srs.md, each
  followed by a line ``Priority: ... | Release: ... | Stories: ... |
  Verification: ... | Status: ...``;
- stories: headings ``### C3-1 Title`` in docs/backlog/*.md;
- tests: files under tests/ whose text names a requirement ID, by convention a
  ``Verifies:`` line in the module docstring.

Problems (the check fails on any):

- a requirement ID appears twice, or its details line is missing or malformed;
- a requirement names a story that isn't in the backlog;
- a test names a requirement that isn't in the SRS;
- an Implemented or Verified requirement whose verification includes T (test)
  has no test naming it;
- traceability.md is not what this script would write (``check`` only).

Usage (from the repository root):
    uv run python scripts/check_traceability.py           # check (CI runs this through tests/test_traceability.py)
    uv run python scripts/check_traceability.py --write   # regenerate docs/requirements/traceability.md
"""

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRS = ROOT / "docs" / "requirements" / "srs.md"
OUTPUT = ROOT / "docs" / "requirements" / "traceability.md"
BACKLOG = ROOT / "docs" / "backlog"
TESTS = ROOT / "tests"

ID = r"EA-(?:FR|NFR)-[A-Z]+-\d{3}"
HEADING = re.compile(rf"^#### ({ID}) (.+)$")
DETAILS = re.compile(
    r"^Priority: (Must|Should|Could|Won't) \| Release: (W1|P\d|L) \| Stories: ([^|]+) \| "
    r"Verification: ([TDIA, ]+) \| Status: (Proposed|Approved|Implemented|Verified)$"
)
STORY = re.compile(r"^### ([A-Z][A-Za-z0-9]*-\d+) ")


@dataclass
class Requirement:
    """One requirement from the SRS, with what links to it."""

    id: str
    title: str
    priority: str
    release: str
    stories: list[str]
    verification: list[str]
    status: str
    tests: list[str] = field(default_factory=list)


def read_requirements(problems: list[str]) -> dict[str, Requirement]:
    """Requirement ID -> requirement, in document order."""
    found: dict[str, Requirement] = {}
    lines = SRS.read_text(encoding="utf-8").splitlines()
    for index, line in enumerate(lines):
        heading = HEADING.match(line)
        if not heading:
            continue
        rid, title = heading.groups()
        details = next((DETAILS.match(x) for x in lines[index + 1 : index + 4] if x.startswith("Priority:")), None)
        if details is None:
            problems.append(f"{rid}: missing or malformed 'Priority: ... | Status: ...' line under its heading")
            continue
        if rid in found:
            problems.append(f"{rid} appears twice in the SRS")
        priority, release, stories, verification, status = details.groups()
        story_ids = [] if stories.strip() == "-" else [s.strip() for s in stories.split(",")]
        found[rid] = Requirement(
            rid, title, priority, release, story_ids, [v.strip() for v in verification.split(",")], status
        )
    return found


def read_stories() -> set[str]:
    """Every story ID in the backlog."""
    ids: set[str] = set()
    for path in sorted(BACKLOG.glob("*.md")):
        for line in path.read_text(encoding="utf-8").splitlines():
            match = STORY.match(line)
            if match:
                ids.add(match.group(1))
    return ids


def link_tests(requirements: dict[str, Requirement], problems: list[str]) -> None:
    """Add to each requirement the test files that name it."""
    for path in sorted(TESTS.glob("*.py")):
        for rid in sorted(set(re.findall(ID, path.read_text(encoding="utf-8")))):
            if rid not in requirements:
                problems.append(f"{path.name} names {rid}, which isn't in the SRS")
            else:
                requirements[rid].tests.append(path.name)


def check(requirements: dict[str, Requirement], stories: set[str], problems: list[str]) -> None:
    """Find unknown stories and tested requirements without tests."""
    for r in requirements.values():
        for story in r.stories:
            if story not in stories:
                problems.append(f"{r.id} names story {story}, which isn't in docs/backlog/")
        if r.status in ("Implemented", "Verified") and "T" in r.verification and not r.tests:
            problems.append(f"{r.id} is {r.status} and verified by test, but no file in tests/ names it")


def matrix(requirements: dict[str, Requirement]) -> str:
    """The traceability matrix as Markdown."""
    rows = [
        "# Requirements traceability matrix",
        "",
        "Generated by `scripts/check_traceability.py --write`. Do not edit by hand.",
        "",
        "| Requirement | Title | Priority | Release | Status | Stories | Tests |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in requirements.values():
        stories = ", ".join(r.stories) or "-"
        tests = ", ".join(r.tests) or "-"
        rows.append(f"| {r.id} | {r.title} | {r.priority} | {r.release} | {r.status} | {stories} | {tests} |")
    return "\n".join(rows) + "\n"


def run(write: bool = False) -> list[str]:
    """Check everything; with ``write``, regenerate the matrix. Returns the problems found."""
    problems: list[str] = []
    requirements = read_requirements(problems)
    link_tests(requirements, problems)
    check(requirements, read_stories(), problems)
    text = matrix(requirements)
    if write:
        OUTPUT.write_text(text, encoding="utf-8")
    elif not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
        problems.append("docs/requirements/traceability.md is out of date: run scripts/check_traceability.py --write")
    return problems


def main() -> None:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="regenerate docs/requirements/traceability.md")
    problems = run(write=parser.parse_args().write)
    for problem in problems:
        print(f"- {problem}")
    if problems:
        sys.exit(f"{len(problems)} traceability problem(s)")
    print("Traceability OK")


if __name__ == "__main__":
    main()
